// @vitest-environment jsdom
import {act} from 'react';
import {createRoot,type Root} from 'react-dom/client';
import {afterEach,beforeEach,expect,it,vi} from 'vitest';
import {RMusicClient,type Endpoint,type Zone} from '@r-music/sdk';
import {DeviceGroups} from './DeviceGroups';
import {presentedZones,syncEligible} from './deviceGroupModel';
const caps=Object.fromEntries(['playback_instance','scheduled_start_v1','scheduled_queue_v1','group_output_v2','group_output_final_v2','measured_listens_v2','host_clock_v1','device_clock_v1','programme_clock_v1'].map(key=>[key,true]));
const endpoints=[0,1].map(i=>({id:`output-${i}`,kind:'alsa',name:`房间 ${i}`,online:true,verified:false,capabilities:{...caps,platform:'linux'}})) as Endpoint[];
const zones=[0,1].map(i=>({id:`zone-${i}`,endpoint_id:`output-${i}`,name:`房间 ${i}`,status:'paused',volume:1,muted:false,repeat:'off',shuffle:false,position:0,updated_at:0,dsp:{enabled:false,normalize:false,preamp_db:0,balance:0,target_lufs:-14,bands:[]},autoplay:{enabled:false,source:'mixed',fallback_local:true},transitions:{fade_in_ms:0,fade_out_ms:0},queue:[],queue_index:0,track:null})) as Zone[];
let host:HTMLDivElement,root:Root;
beforeEach(()=>{vi.stubGlobal('IS_REACT_ACT_ENVIRONMENT',true);host=document.createElement('div');document.body.append(host);root=createRoot(host);});
afterEach(async()=>{await act(async()=>root.unmount());host.remove();vi.restoreAllMocks();vi.unstubAllGlobals();});
it('组合在设备列表中只有一个入口，网页与安卓即使声明能力也不能成为同步成员',()=>{
 expect(syncEligible(endpoints[0])).toBe(true);
 expect(syncEligible({...endpoints[0],kind:'browser'})).toBe(false);
 expect(syncEligible({...endpoints[0],capabilities:{...caps,platform:'android'}})).toBe(false);
 expect(syncEligible({...endpoints[0],online:false})).toBe(false);
 const group={id:'logical',kind:'group',group:{id:'g',zone_ids:['zone-0','zone-1'],endpoint_ids:['output-0','output-1']}} as Endpoint;
 const logical={...zones[0],id:'logical-zone',endpoint_id:'logical'};
 expect(presentedZones([...zones,logical],[...endpoints,group]).map(z=>z.id)).toEqual(['logical-zone']);
});
it('创建只提交设备和队列来源，不再让用户选择歌单或开启临时分组任务',async()=>{
 const api=new RMusicClient('http://qa-core','qa-token'),selected=vi.fn(),refresh=vi.fn(async()=>{});
 const group={id:'g',zone_id:'group-zone',endpoint_id:'logical',zone_ids:['zone-0','zone-1'],source_zone_id:'zone-0',name:'全屋',phase:'ready',revision:1};
 const request=vi.spyOn(api,'request').mockImplementation(async(_path,options)=>options?.method==='POST'?group:{items:[]});
 await act(async()=>root.render(<DeviceGroups api={api} zones={zones} endpoints={endpoints} selected="zone-0" supported onSelect={selected} refresh={refresh} onError={vi.fn()}/>));
 await act(async()=>[...host.querySelectorAll('button')].find(b=>b.textContent==='组合设备')!.click());
 expect(document.body.textContent).not.toContain('选择播放列表');expect(document.body.textContent).toContain('使用哪台设备当前的队列');
 await act(async()=>document.querySelectorAll<HTMLInputElement>('input[type=checkbox]')[1].click());
 await act(async()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='组合为一个设备')!.click());
 const write=request.mock.calls.find(([,options])=>options?.method==='POST')!;
 expect(write[0]).toBe('/device-groups');
 expect(JSON.parse(write[1]!.body as string)).toMatchObject({name:'全屋',zone_ids:['zone-0','zone-1'],source_zone_id:'zone-0'});
 expect(JSON.parse(write[1]!.body as string)).not.toHaveProperty('queue');
 expect(request.mock.calls.some(([path])=>String(path).startsWith('/sync/starts'))).toBe(false);
 expect(selected).toHaveBeenCalledWith('group-zone');expect(refresh).toHaveBeenCalledOnce();
});
it('成员调整保留原组合身份并提交当前修订号',async()=>{
 const api=new RMusicClient('http://qa-core','qa-token'),selected=vi.fn(),refresh=vi.fn(async()=>{});
 const group={id:'g',zone_id:'group-zone',endpoint_id:'logical',zone_ids:['zone-0','zone-1'],source_zone_id:'zone-0',name:'全屋',phase:'ready',revision:7};
 const extra={...zones[0],id:'zone-2',endpoint_id:'output-2'},extraEndpoint={...endpoints[0],id:'output-2'};
 const request=vi.spyOn(api,'request').mockImplementation(async(_path,options)=>options?.method==='PUT'?group:{items:[group]});
 await act(async()=>root.render(<DeviceGroups api={api} zones={[...zones,extra]} endpoints={[...endpoints,extraEndpoint]} selected="group-zone" supported onSelect={selected} refresh={refresh} onError={vi.fn()}/>));
 await act(async()=>[...host.querySelectorAll('button')].find(b=>b.textContent==='调整成员')!.click());
 expect(document.body.textContent).not.toContain('使用哪台设备当前的队列');
 const boxes=[...document.querySelectorAll<HTMLInputElement>('input[type=checkbox]')];
 expect(boxes.filter(b=>b.checked)).toHaveLength(2);
 await act(async()=>boxes[2].click());
 await act(async()=>[...document.querySelectorAll('button')].find(b=>b.textContent==='保存成员')!.click());
 const write=request.mock.calls.find(([,options])=>options?.method==='PUT')!;
 expect(write[0]).toBe('/device-groups/g');
 expect(JSON.parse(write[1]!.body as string)).toEqual({name:'全屋',zone_ids:['zone-0','zone-1','zone-2'],expected_revision:7});
 expect(selected).not.toHaveBeenCalled();expect(refresh).toHaveBeenCalledOnce();
});
it('不同音区共享一个物理输出时，不允许同时选为两个成员',async()=>{
 const api=new RMusicClient('http://qa-core','qa-token');
 const duplicate={...zones[0],id:'duplicate',name:'同一输出的另一个音区'};
 vi.spyOn(api,'request').mockResolvedValue({items:[]});
 await act(async()=>root.render(<DeviceGroups api={api} zones={[...zones,duplicate]} endpoints={endpoints} selected="zone-0" supported onSelect={vi.fn()} refresh={vi.fn()} onError={vi.fn()}/>));
 await act(async()=>[...host.querySelectorAll('button')].find(b=>b.textContent==='组合设备')!.click());
 const duplicateChoice=[...document.querySelectorAll('label')].find(label=>label.textContent?.includes(duplicate.name))!;
 expect(duplicateChoice.querySelector<HTMLInputElement>('input')?.disabled).toBe(true);
 expect([...document.querySelectorAll<HTMLButtonElement>('button')].find(b=>b.textContent==='组合为一个设备')?.disabled).toBe(true);
});
it('编辑时可以看见并移除已离线成员，再选在线输出替换',async()=>{
 const api=new RMusicClient('http://qa-core','qa-token');
 const group={id:'g',zone_id:'group-zone',endpoint_id:'logical',zone_ids:['zone-0','zone-1'],source_zone_id:'zone-0',name:'全屋',phase:'ready',revision:7};
 const extra={...zones[0],id:'zone-2',endpoint_id:'output-2'},extraEndpoint={...endpoints[0],id:'output-2'};
 const request=vi.spyOn(api,'request').mockImplementation(async(_path,options)=>options?.method==='PUT'?{...group,zone_ids:['zone-1','zone-2']}:{items:[group]});
 await act(async()=>root.render(<DeviceGroups api={api} zones={[...zones,extra]} endpoints={[{...endpoints[0],online:false},endpoints[1],extraEndpoint]} selected="group-zone" supported onSelect={vi.fn()} refresh={vi.fn()} onError={vi.fn()}/>));
 await act(async()=>[...host.querySelectorAll('button')].find(b=>b.textContent==='调整成员')!.click());
 const boxes=document.querySelectorAll<HTMLInputElement>('input[type=checkbox]');
 expect(boxes).toHaveLength(3);
 const save=[...document.querySelectorAll('button')].find(b=>b.textContent==='保存成员')!;
 expect(save.disabled).toBe(true);
 await act(async()=>{boxes[0].click();boxes[2].click();});
 expect(save.disabled).toBe(false);
 await act(async()=>save.click());
 const write=request.mock.calls.find(([,options])=>options?.method==='PUT')!;
 expect(JSON.parse(write[1]!.body as string).zone_ids).toEqual(['zone-1','zone-2']);
});
it('在线输出不足时在组合页说明原因，省去进入无法提交的弹窗',async()=>{
 const api=new RMusicClient('http://qa-core','qa-token');
 vi.spyOn(api,'request').mockResolvedValue({items:[]});
 await act(async()=>root.render(<DeviceGroups api={api} zones={zones} endpoints={[endpoints[0],{...endpoints[1],online:false}]} selected="zone-0" supported onSelect={vi.fn()} refresh={vi.fn()} onError={vi.fn()}/>));
 expect(host.querySelector('.device-group-notice')?.textContent).toContain('1 个可组合输出');
 expect([...host.querySelectorAll('button')].find(b=>b.textContent==='组合设备')?.disabled).toBe(true);
});
